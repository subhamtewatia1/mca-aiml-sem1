# slot 01 - basic output
# print() is used to show something on the screen

print("Hello, World!")
print('single quotes also work')

# print with nothing gives an empty line
print()

# many values, comma puts a space between them
print("Python", "is", "fun")

# sep changes what comes between
print("06", "09", "2026", sep="-")

# end changes what comes at the end (default is a new line)
print("this line", end=" ")
print("joins with this one")

# \n = new line, \t = tab
print("line one\nline two")
print("Name:\tSubham")

# triple quotes keep the shape as it is
print("""
+-------------------+
|  MY FIRST PROGRAM |
+-------------------+
""")

# numbers do not need quotes
print(2026)
print(10 + 5)
