# Program 1 - Multiplication Table (Nested for)

for i in range(1, 4):           # outer loop: i = 1, 2, 3
    for j in range(1, 4):       # inner loop: har i ke liye j = 1, 2, 3
        print(i, "*", j, "=", i*j)
# Output:
# 1 * 1 = 1
# 1 * 2 = 2
# 1 * 3 = 3
# 2 * 1 = 2
# 2 * 2 = 4
# 2 * 3 = 6
# 3 * 1 = 3
# 3 * 2 = 6
# 3 * 3 = 9
