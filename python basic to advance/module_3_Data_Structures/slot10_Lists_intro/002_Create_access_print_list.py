# Program 1 - Create, Access, and Print a List

marks = [85, 92, 78, 88, 95]
print(marks)                    # Output: [85, 92, 78, 88, 95]
print(marks[0])                 # Output: 85  (pehla element, index 0)
print(marks[2])                 # Output: 78  (teesra element, index 2)
print(marks[-1])                # Output: 95  (aakhri element, negative index)
print(len(marks))               # Output: 5   (total elements)
