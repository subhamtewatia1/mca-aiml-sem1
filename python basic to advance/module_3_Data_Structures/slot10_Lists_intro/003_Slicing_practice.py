# Program 2 - Slicing Practice
# list[start:stop] -> start se shuru, stop se PEHLE ruk jata hai

marks = [85, 92, 78, 88, 95]
print(marks[1:4])               # Output: [92, 78, 88]  (index 1, 2, 3)
print(marks[:3])                # Output: [85, 92, 78]  (shuru se index 2 tak)
print(marks[2:])                # Output: [78, 88, 95]  (index 2 se end tak)
