# Program 3 - Guided Practice: Complete the Indexing

cities = ["Delhi", "Mumbai", "Chennai", "Kolkata", "Pune"]

# Print the first city
print(cities[0])                # blank -> 0      | Output: Delhi

# Print the last city using negative indexing
print(cities[-1])               # blank -> -1     | Output: Pune

# Print cities from index 1 to 3 (Mumbai, Chennai, Kolkata)
print(cities[1:4])              # blanks -> 1, 4  | Output: ['Mumbai', 'Chennai', 'Kolkata']
