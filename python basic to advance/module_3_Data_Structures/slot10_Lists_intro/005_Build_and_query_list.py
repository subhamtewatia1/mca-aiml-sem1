scores = [72, 85, 90, 64, 78, 88]
print("All scores:", scores)        # Output: All scores: [72, 85, 90, 64, 78, 88]
print("First:", scores[0])          # Output: First: 72
print("Last:", scores[-1])          # Output: Last: 88
print("Middle four:", scores[1:5])  # Output: Middle four: [85, 90, 64, 78]
print("Count:", len(scores))        # Output: Count: 6
