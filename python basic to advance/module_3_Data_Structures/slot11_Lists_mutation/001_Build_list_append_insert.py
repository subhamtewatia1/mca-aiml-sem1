# Program 1 - Build a List with append() and insert()

students = []                       # khaali list
students.append("Alice")            # end me add -> ['Alice']
students.append("Bob")              # end me add -> ['Alice', 'Bob']
students.insert(1, "Charlie")       # index 1 par add -> ['Alice', 'Charlie', 'Bob']
print(students)                     # Output: ['Alice', 'Charlie', 'Bob']
