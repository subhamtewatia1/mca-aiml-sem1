# Program 2 - Set Creation & Operations

a = {1, 2, 3, 4}
b = {3, 4, 5, 6}
print(a | b)                    # Output: {1, 2, 3, 4, 5, 6}  (Union - dono ke sab)
print(a & b)                    # Output: {3, 4}              (Intersection - common)
print(a - b)                    # Output: {1, 2}              (Difference - sirf a me)
